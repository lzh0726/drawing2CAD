"""Generate a fixed, evaluation-only smoke set; not a real-drawing benchmark."""
import argparse
import hashlib
import itertools
import json
from pathlib import Path
import random
from backend.app.cad_runner import run

def generate(output,count=32):
    output=Path(output)
    if output.exists(): raise ValueError('Output directory already exists; refusing to overwrite.')
    candidates=[p for p in itertools.product((60,80,100,120),(50,60,70),(8,12),(16,24)) if p[3] <= min(p[0],p[1])-28]
    random.Random(20261024).shuffle(candidates)
    if not 1<=count<=len(candidates): raise ValueError(f'count must be between 1 and {len(candidates)}')
    output.mkdir(parents=True)
    records=[]
    for index,(length,width,thickness,hole) in enumerate(candidates[:count]):
        sample=output/f'plate-{index:03d}';sample.mkdir()
        params=dict(length=length,width=width,thickness=thickness,hole=hole)
        (sample/'params.json').write_text(json.dumps(params),encoding='utf-8')
        run('demo',sample)
        records.append({'id':sample.name,'drawing':f'{sample.name}/drawing.png','step':f'{sample.name}/model.step','code':f'{sample.name}/model.py','family':'mounting-plate-template','group':'all-mounting-plate-variants','split':'test','source':'generated by this project from a known template','license':'project-generated; no external data','kind':'synthetic-smoke-only','parameters':params,'drawing_sha256':hashlib.sha256((sample/'drawing.png').read_bytes()).hexdigest()})
    (output/'manifest.jsonl').write_text(''.join(json.dumps(r,ensure_ascii=False)+'\n' for r in records),encoding='utf-8')
    (output/'README.txt').write_text('Evaluation-only synthetic smoke set. All variants share one template family. Do not split these variants across training and test. These schematic views are not a real engineering-drawing benchmark. Parameters and STEP are evaluation truth; never send them to the image model.\n',encoding='utf-8')
    return len(records)

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--output',required=True);parser.add_argument('--count',type=int,default=32)
    args=parser.parse_args();print(f'Generated {generate(args.output,args.count)} synthetic evaluation samples.')
